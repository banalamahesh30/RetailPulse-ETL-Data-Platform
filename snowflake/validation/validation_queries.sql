

USE DATABASE REATILPULSE_DW;
USE SCHEMA REATILPULSE_SCHEMA;

-- 1. RECORD COUNT VALIDATION


SELECT 'DIM_CUSTOMER' AS TABLE_NAME, COUNT(*) AS RECORD_COUNT
FROM DIM_CUSTOMER

UNION ALL
SELECT 'DIM_PRODUCT', COUNT(*)
FROM DIM_PRODUCT

UNION ALL
SELECT 'DIM_SELLER', COUNT(*)
FROM DIM_SELLER

UNION ALL
SELECT 'DIM_WAREHOUSE', COUNT(*)
FROM DIM_WAREHOUSE

UNION ALL
SELECT 'DIM_DATE', COUNT(*)
FROM DIM_DATE

UNION ALL
SELECT 'FACT_SALES', COUNT(*)
FROM FACT_SALES

UNION ALL
SELECT 'FACT_PAYMENTS', COUNT(*)
FROM FACT_PAYMENTS

UNION ALL
SELECT 'FACT_SHIPMENTS', COUNT(*)
FROM FACT_SHIPMENTS

UNION ALL
SELECT 'FACT_RETURNS', COUNT(*)
FROM FACT_RETURNS

UNION ALL
SELECT 'FACT_REVIEWS', COUNT(*)
FROM FACT_REVIEWS;



-- 2. DUPLICATE ID VALIDATION


SELECT CUSTOMER_ID, COUNT(*) AS DUPLICATE_COUNT
FROM DIM_CUSTOMER
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 1;

SELECT PRODUCT_ID, COUNT(*) AS DUPLICATE_COUNT
FROM DIM_PRODUCT
GROUP BY PRODUCT_ID
HAVING COUNT(*) > 1;

SELECT SELLER_ID, COUNT(*) AS DUPLICATE_COUNT
FROM DIM_SELLER
GROUP BY SELLER_ID
HAVING COUNT(*) > 1;

SELECT WAREHOUSE_ID, COUNT(*) AS DUPLICATE_COUNT
FROM DIM_WAREHOUSE
GROUP BY WAREHOUSE_ID
HAVING COUNT(*) > 1;

SELECT DATE_KEY, COUNT(*) AS DUPLICATE_COUNT
FROM DIM_DATE
GROUP BY DATE_KEY
HAVING COUNT(*) > 1;

SELECT ORDER_ITEM_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_SALES
GROUP BY ORDER_ITEM_ID
HAVING COUNT(*) > 1;

SELECT PAYMENT_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_PAYMENTS
GROUP BY PAYMENT_ID
HAVING COUNT(*) > 1;

SELECT SHIPMENT_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_SHIPMENTS
GROUP BY SHIPMENT_ID
HAVING COUNT(*) > 1;

SELECT RETURN_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_RETURNS
GROUP BY RETURN_ID
HAVING COUNT(*) > 1;

SELECT REVIEW_ID, COUNT(*) AS DUPLICATE_COUNT
FROM FACT_REVIEWS
GROUP BY REVIEW_ID
HAVING COUNT(*) > 1;



